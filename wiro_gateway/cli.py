@app.command()
def install(
    api_key: str | None = typer.Option(None, "--api-key", help="Wiro API key (or paste at the prompt)"),
    api_secret: str | None = typer.Option(None, "--api-secret", help="Wiro API secret (or paste at the prompt)"),
    no_systemd: bool = typer.Option(False, "--no-systemd", help="Skip systemd user service install"),
    no_wrappers: bool = typer.Option(False, "--no-wrappers", help="Skip codexw / qwen-codex wrapper install"),
    non_interactive: bool = typer.Option(False, "--non-interactive", "-y", help="Re-use existing .env, do not prompt"),
) -> None:
    """One-shot install: .env + systemd service + codexw wrapper. Then 'codexw'."""
    # 1. .env
    if not non_interactive or not (Path.cwd() / ".env").exists():
        init(api_key=api_key, api_secret=api_secret, yes=non_interactive)
    # 2. systemd
    if not no_systemd:
        import subprocess
        r = subprocess.run([str(Path(__file__).parent.parent / "bin" / "install-systemd.sh")])
        if r.returncode != 0:
            raise typer.Exit(r.returncode)
    # 3. wrappers
    if not no_wrappers:
        import subprocess
        r = subprocess.run([str(Path(__file__).parent.parent / "bin" / "install-wrappers.sh")])
        if r.returncode != 0:
            raise typer.Exit(r.returncode)
    # 4. healthz
    s = get_settings()
    if s.wiro_api_key and s.wiro_api_secret:
        url = f"http://{s.gateway_host}:{s.gateway_port}/healthz"
        try:
            import httpx
            r = httpx.get(url, timeout=2.0)
            if r.status_code == 200:
                console.print(f"[bold green]OK[/bold green] gateway is live at {url}")
        except Exception:
            console.print(f"[yellow]gateway not yet reachable at {url} (it may start in a moment)[/yellow]")

    console.print()
    console.print(Panel.fit(
        "[bold green]wiro-gateway is installed.[/bold green]\n\n"
        "  Run [bold cyan]codexw[/bold cyan] in any directory to launch Codex with Qwen 3.8 27B.\n"
        "  Or: [bold cyan]codexw exec \"refactor foo.py\"[/bold cyan]\n\n"
        "  Manage:  systemctl --user {status,restart,stop} wiro-gateway\n"
        "  Logs:     tail -f /tmp/wiro-gateway.log\n"
        "  Uninstall: wiro-gateway uninstall",
        title="All set",
    ))


@app.command()
def uninstall(
    purge_config: bool = typer.Option(False, "--purge", help="Also delete the wiro provider/profile in ~/.codex/"),
    yes: bool = typer.Option(False, "--yes", "-y", help="Don't prompt"),
) -> None:
    """Stop and remove the systemd service, the wrappers, and the codex wiro profile."""
    import subprocess
    if not yes:
        typer.confirm("Remove wiro-gateway systemd service and codex wrappers?", abort=True)
    s = Path(__file__).parent.parent / "bin"
    subprocess.run([str(s / "uninstall-systemd.sh")], check=False)
    # Remove symlinks in ~/.local/bin/
    home_bin = Path.home() / ".local" / "bin"
    for name in ("qwen-codex", "codexw", "codex-wiro", "qwen-claude", "claudew", "claude-wiro"):
        p = home_bin / name
        if p.is_symlink() or p.exists():
            try:
                p.unlink()
            except OSError:
                pass
    if purge_config:
        for p in (Path.home() / ".codex" / "wiro.config.toml",):
            if p.exists():
                p.unlink()
                console.print(f"removed {p}")
        # Remove the [model_providers.wiro] block from the main config if present
        main = Path.home() / ".codex" / "config.toml"
        if main.exists():
            text = main.read_text()
            import re
            new = re.sub(r"\n# --- wiro-gateway:.*?(?=\n\[|\Z)", "", text, flags=re.DOTALL)
            if new != text:
                main.write_text(new)
                console.print(f"purged wiro provider from {main}")
    console.print("[green]wiro-gateway uninstalled.[/green]  .env and source files left in place.")



