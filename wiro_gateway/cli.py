ENV_PATH = Path.cwd() / ".env"


def _read_env() -> dict[str, str]:
    if not ENV_PATH.exists():
        return {}
    out: dict[str, str] = {}
    for line in ENV_PATH.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        k, v = s.split("=", 1)
        out[k.strip()] = v.strip()
    return out


def _write_env(values: dict[str, str]) -> None:
    lines = [
        "# Generated by `wiro-gateway init`. Keep this file private (chmod 600).",
        "",
    ]
    for k, v in values.items():
        lines.append(f"{k}={v}")
    ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        os.chmod(ENV_PATH, 0o600)
    except OSError:
        pass


@app.command()
def init(
    api_key: str | None = typer.Option(None, "--api-key", help="Wiro API key (or paste later)"),
    api_secret: str | None = typer.Option(None, "--api-secret", help="Wiro API secret (or paste later)"),
    model: str = typer.Option("qwen/qwen3-8-27b-uncensored", "--model", help="Default Wiro model path"),
    port: int = typer.Option(8765, "--port", help="Local gateway port"),
    yes: bool = typer.Option(False, "--yes", "-y", help="Don't prompt; use provided flags / .env.example defaults"),
) -> None:
    """Write a fresh .env with your Wiro credentials. Idempotent."""
    current = _read_env()
    if not api_key:
        if current.get("WIRO_API_KEY"):
            api_key = current["WIRO_API_KEY"]
        else:
            api_key = typer.prompt("Wiro API key (from https://wiro.ai/panel -> Projects)")
    if not api_secret:
        if current.get("WIRO_API_SECRET"):
            api_secret = current["WIRO_API_SECRET"]
        else:
            api_secret = typer.prompt("Wiro API secret (Signature-Based projects only)", hide_input=True)
    if current.get("WIRO_MODEL"):
        model = current["WIRO_MODEL"]
    if current.get("GATEWAY_PORT"):
        try:
            port = int(current["GATEWAY_PORT"])
        except ValueError:
            pass

    values = {
        "WIRO_API_KEY": api_key or "",
        "WIRO_API_SECRET": api_secret or "",
        "WIRO_MODEL": model,
        "WIRO_API_BASE": "https://api.wiro.ai/v1",
        "WIRO_WS_BASE": "wss://socket.wiro.ai/v1",
        "GATEWAY_HOST": "127.0.0.1",
        "GATEWAY_PORT": str(port),
        "WIRO_POLL_INTERVAL_SEC": "1.0",
        "WIRO_POLL_TIMEOUT_SEC": "600",
    }
    _write_env(values)
    console.print(Panel.fit(
        f"[green]OK[/green] Wrote [bold]{ENV_PATH}[/bold]\n"
        f"  model : {model}\n  port  : {port}\n"
        "Next: `wiro-gateway doctor` to verify, then `wiro-gateway start`.",
        title="wiro-gateway init",
    ))


@app.command()
def doctor() -> None:
    """Verify config + a tiny Run call against Wiro. Stops on first failure."""
    s = get_settings()
    table = Table(title="wiro-gateway doctor", show_lines=False)
    table.add_column("Check", style="bold")
    table.add_column("Result")
    table.add_column("Detail")
    try:
        s.require_credentials()
        table.add_row("Credentials", "[green]ok[/green]", f"key={s.wiro_api_key[:6]}…")
    except Exception as exc:
        table.add_row("Credentials", "[red]fail[/red]", str(exc))
        console.print(table)
        raise typer.Exit(1)

    import asyncio
    import httpx
    from .auth import auth_headers
    headers = auth_headers(s.wiro_api_key, s.wiro_api_secret)
    try:
        with httpx.Client(timeout=15.0) as c:
            r = c.post(
                f"{s.wiro_api_base}/Run/{s.wiro_model}",
                data={"prompt": "ping", "max_tokens": "8"},
                headers=headers,
            )
        if r.status_code in (200, 201):
            payload = r.json()
            table.add_row(
                "Wiro Run", "[green]ok[/green]",
                f"taskid={payload.get('taskid')} status_endpoint=Task/Detail",
            )
        else:
            table.add_row("Wiro Run", "[red]fail[/red]", f"HTTP {r.status_code}: {r.text[:200]}")
            console.print(table)
            raise typer.Exit(1)
    except Exception as exc:
        table.add_row("Wiro Run", "[red]fail[/red]", str(exc))
        console.print(table)
        raise typer.Exit(1)
    console.print(table)


@app.command()
def start(
    host: str | None = typer.Option(None, "--host"),
    port: int | None = typer.Option(None, "--port"),
    reload: bool = typer.Option(False, "--reload", help="Dev: reload on code change"),
    log_level: str = typer.Option("info", "--log-level"),
) -> None:
    """Start the local FastAPI server (blocking)."""
    s = get_settings()
    s.require_credentials()
    host = host or s.gateway_host
    port = port or s.gateway_port
    import uvicorn
    console.print(f"[bold]wiro-gateway[/bold] {__version__} starting on http://{host}:{port} (model={s.wiro_model})")
    uvicorn.run("wiro_gateway.server:app", host=host, port=port, reload=reload, log_level=log_level)


